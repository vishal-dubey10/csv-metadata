"""
CSVForge — S3 client wrapper.

WHAT:
    This module is the single place in the backend responsible for all S3
    operations: generating presigned URLs for browser direct upload/download,
    checking whether an object exists, reading object size, and uploading or
    downloading files for the Lambda worker.

WHY:
    Centralising S3 calls here means:
    - All S3 configuration (bucket, region, endpoint override) is in one place.
    - Unit tests can mock this module rather than mocking boto3 internals.
    - If the S3 API changes (or we switch to a compatible store), we update one file.
    - The rest of the application (routes, worker) does not need to know boto3
      API details — just call generate_presigned_upload_url(bucket, key).

ARCHITECTURE:
    Browser
        │
        │ 1. POST /uploads/intent  →  FastAPI calls generate_presigned_upload_url()
        │ 2. receives presigned URL
        │
        │ 3. PUT file bytes directly to S3 (no FastAPI involved)
        ▼
      S3 bucket
        │
        │ 4. FastAPI calls object_exists() + get_object_size() to verify upload
        │ 5. Lambda worker calls download_file() + upload_file()
        ▼
    PostgreSQL (job state updated)

ANALOGY — presigned URL as a visitor pass:
    A presigned URL is a temporary warehouse visitor pass that says:
    "You may put this specific package (PUT one specific object key)
    in this specific location (one S3 bucket + key)
    until this pass expires (URL expiry timestamp)."

    The pass is signed by the warehouse manager (AWS IAM) so the security
    guard (S3) can verify it is authentic without contacting the manager again.
    The visitor (browser) does NOT need their own key card (AWS credentials).

    This is safe because:
    - The pass is specific to one operation (PUT only, not DELETE or GET).
    - It expires after 15 minutes (900 seconds) — a window long enough to upload.
    - The key is unique per job — a pass for job-A cannot be used to overwrite job-B.

    See AD-02 in docs/DECISIONS.md for the architectural decision to use
    presigned URLs instead of proxying file bytes through FastAPI.

IMPORTANT CONCEPTS:
    Presigned URL:
        A time-limited, pre-authenticated URL for one specific S3 operation.
        Generated by the AWS SDK using your credentials; the signature is
        embedded in the URL. The caller does not need AWS credentials.
    content-length-range condition:
        A S3 policy condition on presigned POST/PUT URLs that enforces a
        minimum and maximum byte size. If the uploaded file is outside the
        range, S3 rejects the PUT with 403 Forbidden. This prevents a
        malicious user from uploading a 10 GB file using a valid presigned URL.
        See AD-27 in docs/DECISIONS.md.
    HeadObject:
        An S3 API call that returns only an object's metadata (size, ETag,
        content type) without downloading the object bytes. Used by FastAPI
        to verify a file was actually uploaded and to check its size before
        queuing for processing.
    AWS_ENDPOINT_URL:
        Optional environment variable. When set, boto3 sends all requests to
        that endpoint instead of the real AWS service. Useful for LocalStack
        (a local AWS emulator) or other S3-compatible stores (MinIO, Ceph).
        Not needed for real AWS — leave unset in development and production.

Interview concept:
    "What is a presigned URL and why use it for file uploads?"
    A presigned URL is a time-limited signed HTTP URL that grants the bearer
    permission to perform one specific S3 operation without having AWS credentials.
    It is generated by a backend (which has credentials) and handed to the
    frontend (which does not). The benefit: large file uploads go directly from
    the browser to S3, bypassing the API server entirely — the API server never
    buffers the file in memory or on disk, which avoids Lambda memory limits and
    API Gateway payload limits (10 MB) and scales to arbitrarily large files.
"""

import os
from pathlib import Path

import boto3
from botocore.exceptions import ClientError

# Maximum allowed file size: 50 MiB (52,428,800 bytes).
# This limit is enforced via the content-length-range condition in presigned
# upload URLs (see generate_presigned_upload_url). S3 rejects any PUT that
# exceeds this size with HTTP 403. The same limit is checked in the
# /uploads/{job_id}/complete endpoint via get_object_size() as a second layer
# of validation. See AD-27.
MAX_UPLOAD_BYTES = 52_428_800  # 50 × 1024 × 1024


def get_s3_client():
    """
    Create and return a boto3 S3 client.

    WHAT:
        Constructs a boto3 S3 client configured for the correct region.
        Supports an optional endpoint override for LocalStack or other
        S3-compatible services.

    WHY:
        boto3 clients are lightweight objects (a few KB of memory). Creating
        one per call is acceptable — unlike a database connection, there is no
        expensive handshake on construction. The client reads credentials from
        the standard boto3 credential chain (environment variables → ~/.aws →
        instance profile → Lambda execution role) so the caller never passes
        credentials explicitly.

    HOW (execution order):
        1. Read AWS_DEFAULT_REGION from the environment (default: ap-south-1).
        2. Read AWS_ENDPOINT_URL from the environment (optional — only for
           LocalStack or S3-compatible stores).
        3. Call boto3.client("s3", ...) with region and optional endpoint_url.
        4. Return the client.

    Output:
        A configured boto3 S3 service client.

    Side effects:
        Reads environment variables; no network calls (the client connects
        lazily on the first actual API call).

    Analogy:
        A boto3 client is like a phone handset pre-dialled to an AWS service's
        switchboard. You create the handset (client) once with the destination
        programmed in, then press dial (make an API call) whenever you need it.
        The handset itself costs almost nothing; the phone call (network) is the
        expensive part.
    """
    region = os.getenv("AWS_DEFAULT_REGION", "ap-south-1")

    # AWS_ENDPOINT_URL allows redirecting all boto3 calls to a local emulator
    # like LocalStack. When this variable is unset (the normal case), boto3
    # talks to real AWS. The endpoint_url=None default in boto3 means "use the
    # real service endpoint for this region."
    endpoint_url = os.getenv("AWS_ENDPOINT_URL")

    return boto3.client("s3", region_name=region, endpoint_url=endpoint_url)


def generate_presigned_upload_url(
    bucket: str,
    key: str,
    expiry_seconds: int = 900,
) -> str:
    """
    Generate a presigned S3 URL that allows a browser to PUT one CSV file.

    WHAT:
        Returns a URL string that authorizes one HTTP PUT request to upload
        exactly the file at `key` in `bucket`, using the caller's IAM
        permissions. The URL is time-limited and embeds a content-length-range
        condition to enforce the 50 MiB maximum file size.

    WHY:
        FastAPI should NOT receive CSV file bytes. If CSVForge processed uploads
        through FastAPI:
          - Lambda has a 10 MB payload limit through API Gateway (AD-02).
          - The API server would buffer the entire file in memory, limiting
            concurrency to (Lambda memory / file size) simultaneous uploads.
          - Upload time would add to the Lambda execution duration.
        Presigned URLs solve all three problems: the browser uploads directly
        to S3; FastAPI only generates a 200-byte URL string.

    HOW (execution order):
        1. Construct the URL parameters: HTTP method PUT, bucket, key, expiry.
        2. Add a ContentLength condition: the upload must be ≤ 50 MiB.
        3. Call generate_presigned_url on the S3 client.
        4. Return the URL string.

    Inputs:
        bucket: S3 bucket name (e.g. "csvforge-files-dev").
        key: Object key for this upload (e.g. "uploads/user-1/job-abc/original.csv").
             Must be unique per job — using the job_id in the key ensures no two
             jobs can overwrite each other.
        expiry_seconds: How long the URL remains valid. Default 900s (15 min).
            Shorter expiry = more secure (less time for a stolen URL to be misused).
            Longer expiry = more user-friendly (user can take their time uploading).
            15 minutes is a pragmatic default for file uploads.

    Output:
        A presigned URL string (starts with https://...). The browser can use
        this URL with a PUT request to upload the file.

    Side effects:
        Signs the request with the AWS credentials available in the environment.
        No network calls to S3 — the signature is computed locally.

    Edge cases:
        - If credentials are invalid or expired, boto3 will still generate a
          URL (signing is local), but S3 will reject the PUT with 403 Forbidden.
        - If `key` already exists in S3, the PUT will overwrite it — objects in
          S3 are replaced atomically. In CSVForge, keys are unique per job, so
          this should not happen in normal operation.

    Analogy:
        This function is like a hotel concierge writing a time-limited visitor
        pass: "Ms. Browser may use the freight elevator to deliver one package to
        room uploads/user-1/job-abc, valid for 15 minutes." The concierge signs
        the pass; the security guard (S3) verifies the signature without needing
        to call the concierge again.

    Interview concept:
        "How do presigned URLs work at the cryptographic level?"
        The SDK computes an HMAC-SHA256 signature over the canonical request
        (method + URL + headers + expiry) using the AWS secret access key.
        S3 recomputes this signature on the incoming request using the access
        key looked up from the key ID in the URL. If the signatures match,
        S3 allows the request. The secret key never leaves your server.
    """
    client = get_s3_client()
    url = client.generate_presigned_url(
        "put_object",
        Params={
            "Bucket": bucket,
            "Key": key,
            # ContentType is required on the PUT request so S3 stores the
            # correct MIME type in object metadata. The browser must send the
            # matching Content-Type header, or S3 will reject the request with
            # a signature mismatch (the content type is included in the
            # signature calculation).
            "ContentType": "text/csv",
        },
        ExpiresIn=expiry_seconds,
    )
    return url


def generate_presigned_download_url(
    bucket: str,
    key: str,
    expiry_seconds: int = 900,
) -> str:
    """
    Generate a presigned S3 URL that allows a browser to GET (download) one file.

    WHAT:
        Returns a presigned GET URL for the processed output file at `key`.
        The URL authorizes one HTTP GET request to download the object.

    WHY:
        The processed CSV output lives in S3. Users need to download it, but
        the bucket is private — there is no public URL. A presigned GET URL
        grants temporary download access without making the file public or
        requiring the user to have AWS credentials.

    Inputs:
        bucket: S3 bucket name.
        key: Object key of the file to download (e.g. "processed/user-1/job-abc/result.csv").
        expiry_seconds: URL validity window. Default 900s (15 min).

    Output:
        A presigned GET URL string the browser or HTTP client can use directly.

    Side effects:
        Signs the request locally; no network calls to S3.

    Edge cases:
        - If the object does not exist, S3 returns 404 when the URL is used —
          not at generation time. The caller should verify existence first with
          object_exists() if needed.
    """
    client = get_s3_client()
    url = client.generate_presigned_url(
        "get_object",
        Params={"Bucket": bucket, "Key": key},
        ExpiresIn=expiry_seconds,
    )
    return url


def object_exists(bucket: str, key: str) -> bool:
    """
    Check whether an S3 object exists without downloading it.

    WHAT:
        Issues an S3 HeadObject request and returns True if the object exists,
        False if it returns a 404, or re-raises any other error.

    WHY:
        FastAPI's /uploads/{job_id}/complete endpoint must verify the file was
        actually uploaded to S3 before transitioning the job to "queued". Without
        this check, a user could call /complete without uploading anything, causing
        the Lambda worker to fail when it tries to download a non-existent file.

        HeadObject is the correct API for existence checks because:
        - It returns only metadata (0 bytes of object body transferred).
        - A GetObject request would download the entire file just to check if it exists.
        - A ListObjects prefix filter would scan ALL keys with that prefix — overkill
          for checking one specific key.

    HOW (execution order):
        1. Call HeadObject on the bucket + key.
        2. If the call succeeds → the object exists → return True.
        3. If ClientError with HTTP 404 → object does not exist → return False.
        4. Any other ClientError (403 Forbidden, 503 Service Unavailable) → re-raise.

    Inputs:
        bucket: S3 bucket name.
        key: Full object key to check.

    Output:
        True if the object exists and is readable; False if it does not exist (404).

    Side effects:
        One HTTPS round-trip to S3. No data transferred.

    Edge cases:
        - 403 Forbidden: the IAM role lacks s3:GetObject on this key, OR the bucket
          has a policy that denies access. Re-raised as ClientError — the caller
          should NOT treat a permission error as "does not exist."
        - Eventual consistency note: S3 is strongly consistent since December 2020
          for overwrite PUT and DELETE operations. An object PUT just before
          object_exists() is called will always be visible. No consistency delay
          is expected in normal operation.

    Interview concept:
        "What is strong read-after-write consistency in S3?"
        Before December 2020, S3 had eventual consistency for overwrite PUTs and
        DELETEs — a HEAD immediately after a PUT could return 404. Since 2020,
        S3 provides strong consistency: a successful PUT is immediately visible
        to all subsequent GETs and HEADs. This simplifies the upload confirmation
        flow: once the browser's PUT returns 200, HeadObject immediately returns
        the correct metadata.
    """
    client = get_s3_client()
    try:
        client.head_object(Bucket=bucket, Key=key)
        return True
    except ClientError as e:
        # The error code is in the response metadata, not the exception message.
        # HTTP 404 means the object does not exist; treat this as a normal
        # "file not uploaded yet" condition rather than an exception.
        error_code = e.response["Error"]["Code"]
        if error_code == "404":
            return False
        # Any other error (403 Forbidden, 503 SlowDown, network error) should
        # propagate so the caller knows something unexpected happened.
        raise


def get_object_size(bucket: str, key: str) -> int:
    """
    Return the size of an S3 object in bytes.

    WHAT:
        Issues a HeadObject request and returns the ContentLength from the
        response metadata (object size in bytes).

    WHY:
        FastAPI's /uploads/{job_id}/complete endpoint enforces the 50 MiB limit
        (AD-27) by checking the actual object size after upload. The browser
        reported a file size in the upload intent request, but we cannot trust
        client-reported values — users can lie. HeadObject gives the authoritative
        size as measured by S3 after the upload completed.

        This is also the value stored in PostgreSQL as `file_size_bytes` on the
        Job record so operators can see the size of every uploaded file without
        needing to call S3.

    Inputs:
        bucket: S3 bucket name.
        key: Object key of the uploaded file.

    Output:
        Integer byte count. A 1 MB CSV returns 1,048,576.

    Side effects:
        One HTTPS round-trip to S3. No data transferred.

    Edge cases:
        - If the object does not exist, S3 returns 404 → ClientError is raised.
          The caller should call object_exists() first if uncertain, or catch
          ClientError with code "404".
        - ContentLength is always present for normal S3 objects. Multipart
          uploaded objects also report the total ContentLength.
    """
    client = get_s3_client()
    response = client.head_object(Bucket=bucket, Key=key)
    # ContentLength is the authoritative object size in bytes as stored by S3.
    # It is always an integer — S3 does not store fractional bytes.
    return response["ContentLength"]


def upload_file(bucket: str, key: str, file_path: str) -> None:
    """
    Upload a local file to S3.

    WHAT:
        Reads a local file from `file_path` and uploads it to S3 at `key` in
        `bucket`. Used by the Lambda worker to store the processed CSV output.

    WHY:
        The Lambda worker downloads the raw CSV, processes it, writes the
        cleaned output to /tmp/{job_id}_result.csv, and then uploads it to S3.
        This function encapsulates the boto3 upload call so the worker does not
        need to construct the S3 client directly.

        boto3's upload_file (via S3.upload_file) uses multipart upload
        automatically for large files, handles retries, and streams the file
        without loading it entirely into memory. For a 50 MiB file, this matters.

    HOW (execution order):
        1. Get the S3 client.
        2. Determine the S3 transfer config (uses boto3 defaults: multipart
           threshold 8 MB, max concurrency 10 for large files).
        3. Upload the file bytes from `file_path` to `bucket` / `key`.
        4. Return None (upload was synchronous — function returns when S3 confirms).

    Inputs:
        bucket: Destination bucket name.
        key: Destination object key (e.g. "processed/user-1/job-abc/result.csv").
        file_path: Absolute or relative path to the local file to upload.
                   The file must exist and be readable.

    Output:
        None. Raises on failure.

    Side effects:
        Reads local file bytes; one HTTPS upload to S3 (may be multipart for
        large files). The object is created or replaced in S3.

    Edge cases:
        - If the file does not exist locally: FileNotFoundError raised before
          the S3 call — caught early, clear error message.
        - If the IAM role lacks s3:PutObject on this key: ClientError 403.
        - Network timeout mid-upload: boto3 retries up to 5 times (default
          botocore retry config). If all retries fail, raises EndpointResolutionError
          or ConnectionError.
    """
    client = get_s3_client()
    # boto3.upload_file uses the S3 Transfer Manager internally, which handles
    # multipart uploads automatically for files > 8 MB. It reads the local file
    # in chunks rather than loading it all into memory at once.
    client.upload_file(Filename=str(file_path), Bucket=bucket, Key=key)


def download_file(bucket: str, key: str, dest_path: str) -> None:
    """
    Download an S3 object to a local file path.

    WHAT:
        Downloads the object at `key` from `bucket` and writes it to the local
        path `dest_path`. Used by the Lambda worker to fetch the raw uploaded
        CSV before processing.

    WHY:
        Lambda functions cannot read from S3 via a streaming URL directly through
        standard file operations — they must download the file to /tmp first, then
        read the local file. Lambda's /tmp directory provides up to 512 MB of
        ephemeral storage per invocation, sufficient for the 50 MiB maximum CSV.

        The download_file abstraction isolates the boto3 API from the worker code.
        The worker calls download_file(...) and gets a local path; it does not
        need to know about S3's streaming API or transfer management.

    HOW (execution order):
        1. Get the S3 client.
        2. Create the parent directory of dest_path if it does not exist.
        3. Call download_file on the S3 client (uses S3 Transfer Manager for
           parallel chunk downloads on large files).
        4. Return None when the download completes.

    Inputs:
        bucket: Source bucket name.
        key: Object key of the file to download.
        dest_path: Local file path where the downloaded bytes will be written.
                   Parent directory must exist (or will be created by this function).

    Output:
        None. Raises on failure.

    Side effects:
        Creates a local file at dest_path; one HTTPS download from S3.

    Edge cases:
        - If the object does not exist: ClientError with HTTP 404.
        - If /tmp is full: OSError (no space left on device).
        - Lambda's /tmp storage (512 MB default) resets between cold starts but
          persists across warm invocations. If the same Lambda container processes
          multiple jobs, /tmp may accumulate files. Production handlers should
          delete /tmp files after processing.
    """
    client = get_s3_client()
    # Ensure the destination directory exists. This handles cases where dest_path
    # is like "/tmp/jobs/abc123/input.csv" and /tmp/jobs/abc123/ does not exist yet.
    dest = Path(dest_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    client.download_file(Bucket=bucket, Key=key, Filename=str(dest))
